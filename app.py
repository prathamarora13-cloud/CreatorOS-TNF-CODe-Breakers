# ---------- Database ----------
def get_connection():
    return sqlite3.connect(DB_PATH)

def init_db():
    with get_connection() as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS projects (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                title TEXT NOT NULL,
                tool TEXT NOT NULL,
                topic TEXT NOT NULL,
                platform TEXT NOT NULL,
                tone TEXT NOT NULL,
                content TEXT NOT NULL,
                created_at TEXT NOT NULL
            )
        """)
        conn.commit()

def save_project(title, tool, topic, platform, tone, content):
    with get_connection() as conn:
        conn.execute(
            """INSERT INTO projects
               (title, tool, topic, platform, tone, content, created_at)
               VALUES (?, ?, ?, ?, ?, ?, ?)""",
            (title, tool, topic, platform, tone, content,
             datetime.now().strftime("%Y-%m-%d %H:%M:%S"))
        )
        conn.commit()

def load_projects(limit=100):
    with get_connection() as conn:
        return conn.execute(
            """SELECT id, title, tool, topic, platform, tone, content, created_at
               FROM projects ORDER BY id DESC LIMIT ?""",
            (limit,)
        ).fetchall()

def delete_project(project_id):
    with get_connection() as conn:
        conn.execute("DELETE FROM projects WHERE id = ?", (project_id,))
        conn.commit()

init_db()

# ---------- Content generation ----------
def demo_generate(tool, topic, platform, duration, tone, audience, extra):
    """Local demonstration mode; outputs are templates, not generated by an AI model."""
    topic_clean = topic.strip() or "your next creative project"
    extra_line = f"\n\nAdditional direction: {extra.strip()}" if extra.strip() else ""

    if tool == "Idea Generator":
        return f"""# Content Ideas: {topic_clean}

1. **The Unexpected Beginning** — Open with a surprising visual or question, then reveal the story behind {topic_clean}.
2. **A Day in the Process** — Show the preparation, behind-the-scenes moments, and final result.
3. **Before vs. After** — Compare the starting point with the finished outcome.
4. **Three Things to Know** — Share three useful or surprising facts about {topic_clean}.
5. **The Story Behind It** — Explain the inspiration, challenge, and lesson.

**Suggested platform:** {platform}
**Tone:** {tone}
**Audience:** {audience}

Demo mode note: These are starter templates. Connect an AI API for tailored AI-generated ideas.{extra_line}"""

    if tool == "Script Writer":
        return f"""# Short-Form Video Script: {topic_clean}

**Platform:** {platform} | **Duration target:** {duration} | **Tone:** {tone}

### Scene 1 — Hook (first few seconds)
**Visual:** Start with a close-up, movement, or an intriguing establishing shot.
**Voice-over/dialogue:** “Have you ever wondered what makes {topic_clean} worth remembering?”

### Scene 2 — Build the story
**Visual:** Show the process, context, or key details using 2–3 short shots.
**Voice-over/dialogue:** “Every detail has a story. Here’s the part people usually miss…”

### Scene 3 — Main moment
**Visual:** Show the most interesting result, reveal, or turning point.
**Voice-over/dialogue:** “This is where the idea comes together.”

### Scene 4 — Ending
**Visual:** Finish on a memorable shot or clear final frame.
**Voice-over/dialogue:** “What would you create next?”

**Editing notes:** Keep cuts purposeful, make on-screen text readable, and match the pacing to the music.
**Audience:** {audience}{extra_line}

Demo mode note: This is a reusable script template, not an AI-generated final script."""

    if tool == "Caption Generator":
        return f"""# Caption Pack: {topic_clean}

### Option 1 — Storytelling
Every frame has a story. This is ours. 🎬

### Option 2 — Short and bold
A new idea. A fresh perspective. ✨

### Option 3 — Behind the scenes
The final result is only one part of the journey. Here’s a little look behind the scenes.

### Suggested hashtags
#{''.join(word.capitalize() for word in topic_clean.split() if word.isalnum())} #ContentCreation #BehindTheScenes #CreativeProcess #VideoEditing

**Platform:** {platform} | **Tone:** {tone}
**Audience:** {audience}{extra_line}

Demo mode note: Review hashtags and caption wording before posting."""

    return f"""# Shot List: {topic_clean}

| Shot | Framing / movement | What to capture | Purpose |
|---|---|---|---|
| 1 | Wide establishing shot | Location and environment | Set the scene |
| 2 | Medium shot | Main subject preparing or entering | Introduce the subject |
| 3 | Close-up | Important detail, hands, object, or expression | Add visual interest |
| 4 | Over-the-shoulder / POV | Subject interacting with the environment | Make the viewer feel involved |
| 5 | Detail montage | 2–4 short supporting clips | Build pace |
| 6 | Hero shot | Best-looking final result | Deliver the main moment |
| 7 | Closing wide shot | Subject or scene settling | Give the story an ending |

**Platform:** {platform} | **Duration target:** {duration}
**Tone:** {tone} | **Audience:** {audience}

**Production tips:** Record a few seconds of extra footage, check focus and exposure, and capture clean ambient audio when useful.{extra_line}

Demo mode note: Adapt the shot list to your location, equipment, and available time."""

def ai_generate(tool, topic, platform, duration, tone, audience, extra):
    api_key = os.getenv("OPENAI_API_KEY", "").strip()
    model = os.getenv("OPENAI_MODEL", "gpt-5.5").strip() or "gpt-5.5"

    if not api_key or api_key == "your_api_key_here" or OpenAI is None:
        return demo_generate(tool, topic, platform, duration, tone, audience, extra), "Demo mode"

    instructions = (
        "You are CreatorOS, a practical assistant for social-media creators, student filmmakers, "
        "editors, and small creative teams. Create original, useful content. Be specific and organized. "
        "Do not claim the output is guaranteed to go viral. Keep the result appropriate for a college project."
    )
    prompt = f"""Create the following deliverable.

Tool: {tool}
Topic: {topic}
Platform: {platform}
Target duration: {duration}
Tone/style: {tone}
Target audience: {audience}
Additional instructions: {extra if extra.strip() else "None"}

Requirements:
- Use clear headings and practical details.
- Match the selected tool.
- For scripts, include scenes and dialogue/voice-over.
- For captions, provide multiple options and relevant hashtags.
- For shot lists, provide shot type, action, and purpose.
- For ideas, provide distinct ideas with a short explanation.
"""
    try:
        client = OpenAI(api_key=api_key)
        response = client.responses.create(
            model=model,
            instructions=instructions,
            input=prompt,
        )
        output = getattr(response, "output_text", "").strip()
        if not output:
            raise RuntimeError("The AI service returned an empty response.")
        return output, f"AI mode ({model})"
    except Exception as exc:
        # Keep the app usable if the API is unavailable.
        return (
            demo_generate(tool, topic, platform, duration, tone, audience, extra)
            + f"\n\n---\n**AI connection note:** The API request did not complete ({type(exc).__name__}). "
              "Check your API key, model access, internet connection, and API billing. "
              "The app has shown a demo template instead.",
            "Demo mode (AI request unavailable)"
        )

